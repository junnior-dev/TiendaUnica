-- =============================================================================
--  Requiere: 01 (tabla negocio). Es idempotente:
--     psql -d tienda -v ON_ERROR_STOP=1 -f 21_calendario_fiscal.sql
--
--  Fuente: Providencia SNAT/2025/000091 (Calendario de Sujetos Pasivos Especiales y Agentes de Retención 2026; reimpresa en la
--  Gaceta Oficial 43.283 del 23-dic-2025). Los datos se tomaron de la publicación de un medio y se contrastaron con las fechas de
--  enero de otra fuente (PwC Venezuela): VERIFÍCALOS contra la Gaceta o el portal del SENIAT. Si una fecha no coincide, corrígela
--  aquí (UPDATE calendario_fiscal SET fecha_limite = ... WHERE ...). Para 2027 se cargan las filas nuevas con el mismo formato.
--
--  Obligaciones cargadas:
--     IVA            IVA, anticipos de ISLR, IGTF y retenciones de IVA, por quincena. Período 1 al 15 vence en la 2.ª mitad del mismo
--                    mes; período 16 al último día vence en la 1.ª mitad del mes siguiente.
--     ISLR_ESTIMADA  Declaración estimada de ISLR (por dígito del RIF).
--  No cargadas: retenciones de ISLR por fecha de pago, autoliquidación anual y las fechas de contribuyentes ordinarios.
--  El calendario NO descuenta feriados ni días no hábiles: el SENIAT los trata en sus avisos.
-- =============================================================================
SET search_path = tienda, public;

CREATE TABLE IF NOT EXISTS calendario_fiscal (
    obligacion     varchar(20) NOT NULL CHECK (obligacion IN ('IVA','ISLR_ESTIMADA')),
    digito         smallint    NOT NULL CHECK (digito BETWEEN 0 AND 9),
    periodo_desde  date        NOT NULL,
    periodo_hasta  date        NOT NULL,
    fecha_limite   date        NOT NULL,
    PRIMARY KEY (obligacion, digito, periodo_desde),
    CHECK (periodo_hasta >= periodo_desde)
);
COMMENT ON TABLE calendario_fiscal IS 'Vencimientos de sujetos pasivos especiales por último dígito del RIF (Providencia SNAT/2025/000091). Verifica contra la Gaceta.';

CREATE TABLE IF NOT EXISTS calendario_presentada (
    obligacion     varchar(20) NOT NULL,
    periodo_desde  date        NOT NULL,
    presentada_en  date        NOT NULL,
    referencia     varchar(60),
    usuario_id     bigint REFERENCES usuarios(id),
    created_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (obligacion, periodo_desde)
);
COMMENT ON TABLE calendario_presentada IS 'Declaraciones que el negocio ya presentó (marca manual: el sistema no se conecta al portal del SENIAT).';

