-- Último dígito del RIF del negocio (el que decide su fecha).
CREATE OR REPLACE FUNCTION fn_digito_rif_negocio() RETURNS smallint LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN rif ~ '[0-9]$' THEN right(rif, 1)::smallint END FROM negocio LIMIT 1
$$;

-- Próximos vencimientos (y los vencidos sin marcar de los últimos 45 días) del negocio. Solo aplica a contribuyentes especiales.
CREATE OR REPLACE FUNCTION fn_proximos_vencimientos(p_hoy date DEFAULT NULL, p_limite int DEFAULT 6)
RETURNS TABLE (obligacion text, titulo text, periodo_desde date, periodo_hasta date, fecha_limite date, dias int, presentada boolean, presentada_en date)
LANGUAGE sql STABLE AS $$
    SELECT c.obligacion::text,
           CASE c.obligacion WHEN 'IVA' THEN 'IVA, anticipo de ISLR, IGTF y retenciones de IVA'
                             ELSE 'Declaración estimada de ISLR' END,
           c.periodo_desde, c.periodo_hasta, c.fecha_limite,
           (c.fecha_limite - COALESCE(p_hoy, fn_hoy()))::int,
           (p.obligacion IS NOT NULL), p.presentada_en
      FROM calendario_fiscal c
      LEFT JOIN calendario_presentada p ON p.obligacion = c.obligacion AND p.periodo_desde = c.periodo_desde
     WHERE c.digito = fn_digito_rif_negocio()
       AND (SELECT es_contribuyente_especial FROM negocio LIMIT 1)
       AND c.fecha_limite >= COALESCE(p_hoy, fn_hoy()) - 45
     ORDER BY c.fecha_limite, c.obligacion
     LIMIT GREATEST(p_limite, 1)
$$;

CREATE OR REPLACE FUNCTION fn_marcar_presentada(p_obligacion text, p_periodo_desde date, p_fecha date, p_referencia text, p_usuario_id bigint) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM calendario_fiscal WHERE obligacion = p_obligacion AND periodo_desde = p_periodo_desde AND digito = fn_digito_rif_negocio()) THEN
        RAISE EXCEPTION 'Ese vencimiento no está en tu calendario' USING ERRCODE = 'TV006'; END IF;
    IF p_fecha IS NULL OR p_fecha > fn_hoy() THEN RAISE EXCEPTION 'La fecha de presentación no puede ser futura' USING ERRCODE = 'TV006'; END IF;
    INSERT INTO calendario_presentada (negocio_id, obligacion, periodo_desde, presentada_en, referencia, usuario_id)
    VALUES (fn_negocio_actual(), p_obligacion, p_periodo_desde, p_fecha, NULLIF(trim(p_referencia), ''), p_usuario_id)
    ON CONFLICT (negocio_id, obligacion, periodo_desde) DO UPDATE SET presentada_en = EXCLUDED.presentada_en, referencia = EXCLUDED.referencia, usuario_id = EXCLUDED.usuario_id;
END $$;

CREATE OR REPLACE FUNCTION fn_desmarcar_presentada(p_obligacion text, p_periodo_desde date) RETURNS void LANGUAGE sql AS $$
    DELETE FROM calendario_presentada WHERE obligacion = p_obligacion AND periodo_desde = p_periodo_desde
$$;
